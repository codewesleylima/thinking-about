import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { capture, runDocker } from '../src/executor.js';
import { makeFixture } from '../src/demo.js';
import { Workspace } from '../src/workspace.js';
import { invariant } from '../src/util.js';
const info = await capture('docker', ['info', '--format', '{{.ServerVersion}}']);
invariant(info.exitCode === 0, `Docker indisponível: ${info.output}`);
const { root, config } = await makeFixture();
await writeFile(path.join(root, '.env'), 'WZZY_CANARY=never-mount-this');
const probe = `const assert = require('node:assert/strict'); const fs = require('node:fs'); const net = require('node:net');
assert.equal(process.getuid(),65534); assert.equal(process.env.OPENAI_API_KEY,undefined);
assert.equal(fs.existsSync('/workspace/.env'),false); assert.equal(fs.existsSync('/workspace/.wzzy'),false);
assert.throws(()=>fs.writeFileSync('/workspace/src/eligibility.js','bad')); assert.throws(()=>fs.writeFileSync('/etc/wzzy-probe','bad'));
fs.writeFileSync('/tmp/wzzy-probe','ok');
const socket=net.connect({host:'1.1.1.1',port:443}); socket.setTimeout(1000);
socket.on('connect',()=>{console.error('unexpected network');process.exit(1)});
socket.on('error',()=>{console.log('filesystem/network/uid/credentials probes passed');process.exit(0)});
socket.on('timeout',()=>{socket.destroy();console.log('network unavailable; filesystem/uid/credentials probes passed');process.exit(0)});`;
config.commands = { probe: { argv: ['node', '-e', probe], verification: true },
  timeout: { argv: ['node', '-e', "require('node:child_process').spawn(process.execPath,['-e','setInterval(()=>{},1000)'],{stdio:'ignore'});setInterval(()=>{},1000)"], verification: true } };
const ws = new Workspace(root, config);
const probeResult = await runDocker(ws, 'probe'); assert.equal(probeResult.passed, true, JSON.stringify(probeResult));
config.limits.commandTimeoutMs = 1000;
const timeoutResult = await runDocker(ws, 'timeout'); assert.equal(timeoutResult.timedOut, true); assert.equal(timeoutResult.cleanupKnown, true); assert.equal(timeoutResult.passed, false);
const containers = await capture('docker', ['ps', '-a', '--filter', 'name=wzzy-', '--format', '{{.Names}}']);
invariant(containers.exitCode === 0, 'Não foi possível conferir containers restantes');
console.log(JSON.stringify({ kind: 'real_docker_smoke', docker: info.output.trim(), root, probe: probeResult, timeout: timeoutResult, remainingWzzyContainers: containers.output.trim() }, null, 2));
